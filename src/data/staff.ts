export function getStaffForDepartment(departmentId: string): StaffMember[] {
  const order = { HOD: 0, Faculty: 1, Support: 2 } as const;
  return staff
    .filter((s) => s.departmentId === departmentId)
    .sort((a, b) => order[a.rankGroup] - order[b.rankGroup] || a.name.localeCompare(b.name));
}

export function getStaffById(id: string): StaffMember | undefined {
  return staff.find((s) => s.id === id);
}
